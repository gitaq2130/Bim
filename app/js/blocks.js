// 삽입 → 실제 좌표 엔티티 목록
export function expandInsert(ins, blocks) {
  const def = blocks?.[ins.name] || LIBRARY[ins.name]; if (!def) return [];
  const a = (ins.rot || 0) * D, s = ins.sc || 1;
  const f = (p) => { const q = rot([p[0] * s, p[1] * s], a); return [q[0] + ins.p[0], q[1] + ins.p[1]]; };
  return def.map(e => {
    const n = { ...e, layer: ins.layer };
    if (e.a) n.a = f(e.a); if (e.b) n.b = f(e.b); if (e.c) n.c = f(e.c); if (e.p) n.p = f(e.p);
    if (e.pts) n.pts = e.pts.map(f); if (e.r) n.r = e.r * s; if (e.h) n.h = e.h * s;
    if (e.t === 'arc') { n.a0 = e.a0 + a; n.a1 = e.a1 + a; }
    if (e.t === 'text') n.rot = (e.rot || 0) + (ins.rot || 0);
    return n;
  });
}
